ALTER TABLE transactions_service.transactions ADD COLUMN IF NOT EXISTS idempotency_key VARCHAR(128);
ALTER TABLE transactions_service.transactions ADD COLUMN IF NOT EXISTS idempotency_hash VARCHAR(64);

CREATE UNIQUE INDEX IF NOT EXISTS transactions_user_idempotency
    ON transactions_service.transactions (user_id, idempotency_key);

CREATE TABLE IF NOT EXISTS transactions_service.event_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id BIGINT NOT NULL REFERENCES transactions_service.transactions (id) ON DELETE CASCADE,
    payload VARCHAR(4000) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    published_at TIMESTAMP
);

CREATE INDEX IF NOT EXISTS event_outbox_unpublished
    ON transactions_service.event_outbox (published_at, id);
